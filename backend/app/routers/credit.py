def _row_to_response(
    application: LoanApplication,
    customer: User,
    product: LoanProduct,
    loan_status: LoanStatus | None,
) -> CreditApplicationResponse:
    """Builds the response from already-fetched rows — the shared tail end
    of both `_to_response` (single-item, one extra query for loan_status is
    fine) and the bulk list endpoints below (which join loan_status in
    directly so this never runs per-row in a loop, avoiding the N+1 those
    endpoints used to have)."""
    return CreditApplicationResponse(
        id=application.id,
        customer_full_name=customer.full_name,
        customer_email=customer.email,
        loan_product_name=product.name,
        amount_requested=application.amount_requested,
        status=application.status,
        review_notes=application.review_notes,
        reviewed_at=application.reviewed_at,
        created_at=application.created_at,
        loan_status=loan_status.value if loan_status else None,
    )


def _to_response(
    session: Session, application: LoanApplication, customer: User, product: LoanProduct
) -> CreditApplicationResponse:
    loan_status = session.exec(select(Loan.status).where(Loan.application_id == application.id)).first()
    return _row_to_response(application, customer, product, loan_status)


def create_loan_for_application(
    session: Session, application: LoanApplication, product: LoanProduct
) -> tuple[Loan, date]:
    """Shared by normal approval and the system_administrator override (§8) that
    reactivates a wrongly-rejected application — both must produce an
    identical Loan + RepaymentSchedule, just reached by a different decision
    path. CLAUDE.md §13: Decimal end to end, never float.
    """
    principal = application.amount_requested
    schedule_result = generate_schedule(
        principal=principal,
        rate_percent=product.interest_rate,
        interest_model=product.interest_model,
        term_days=product.repayment_period_days,
        installment_count=product.installment_count,
        start_date=date.today(),
    )
    total_repayable = schedule_result.total_repayable

    loan = Loan(
        application_id=application.id,
        customer_id=application.customer_id,
        loan_product_id=product.id,
        company_id=application.company_id,
        principal=principal,
        interest_rate=product.interest_rate,
        total_repayable=total_repayable,
        outstanding_balance=total_repayable,
        status=LoanStatus.approved,
    )
    session.add(loan)
    session.flush()

    # CLAUDE.md §19 borrower transparency: principal vs interest per
    # installment, not just "amount due".
    for installment in schedule_result.installments:
        session.add(
            RepaymentSchedule(
                loan_id=loan.id,
                company_id=application.company_id,
                installment_number=installment.installment_number,
                due_date=installment.due_date,
                amount_due=installment.amount_due,
                principal_component=installment.principal_component,
                interest_component=installment.interest_component,
            )
        )
    due_date = schedule_result.installments[-1].due_date
    return loan, due_date


def _get_application_bundle(session: Session, application_id: int) -> tuple[LoanApplication, User, LoanProduct]:
    # session.get is tenant-scoped — another company's application_id comes
    # back None here, indistinguishable from "doesn't exist".
    application = session.get(LoanApplication, application_id)
    if application is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Application not found")
    customer = session.get(User, application.customer_id)
    product = session.get(LoanProduct, application.loan_product_id)
    if customer is None or product is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Application not found")
    return application, customer, product


def _credit_application_base_query():
    """One joined query (application + customer + product + loan status)
    instead of 1 + 3N round trips per row — the pattern every list endpoint
    below now shares."""
    return (
        select(LoanApplication, User, LoanProduct, Loan.status)
        .join(User, User.id == LoanApplication.customer_id)
        .join(LoanProduct, LoanProduct.id == LoanApplication.loan_product_id)
        .outerjoin(Loan, Loan.application_id == LoanApplication.id)
    )


@router.get("/queue", response_model=list[CreditApplicationResponse])
def get_credit_queue(
    session: Session = Depends(get_session),
    officer: User = Depends(require_role(UserRole.credit_officer)),
) -> list[CreditApplicationResponse]:
    rows = session.exec(
        _credit_application_base_query()
        .where(LoanApplication.status == ApplicationStatus.pending)
        .order_by(LoanApplication.created_at)
    ).all()
    return [_row_to_response(a, c, p, ls) for a, c, p, ls in rows]


