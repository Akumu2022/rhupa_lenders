@router.post("/applications/{application_id}/approve", response_model=LoanApprovalResponse)
def approve_application(
    application_id: int,
    body: CreditDecisionRequest,
    session: Session = Depends(get_session),
    officer: User = Depends(require_role(UserRole.credit_officer)),
) -> LoanApprovalResponse:
    application, customer, product = _get_application_bundle(session, application_id)

    # CLAUDE.md §14: compare-and-set, never a blind UPDATE.
    result = session.execute(
        update(LoanApplication)
        .where(LoanApplication.id == application_id, LoanApplication.status == ApplicationStatus.pending)
        .values(
            status=ApplicationStatus.approved,
            reviewed_by=officer.id,
            reviewed_at=datetime.now(timezone.utc),
            review_notes=body.notes,
        )
    )
    if result.rowcount == 0:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Application is not pending review")

    loan, due_date = create_loan_for_application(session, application, product)

    # CLAUDE.md §19 light exception monitoring: an approval landed within a
    # minute of submission is fast enough to be worth a second look — flagged
    # onto the exceptions list via is_anomaly, not blocked and not rewriting
    # the officer's own notes (advisory, not automation deciding).
    seconds_to_decision = (datetime.now(timezone.utc) - as_utc(application.created_at)).total_seconds()
    is_anomaly = seconds_to_decision < 60

    write_audit(
        session,
        actor=officer,
        action=AuditAction.APPLICATION_APPROVE.value,
        entity_type="LoanApplication",
        entity_id=application_id,
        reason=body.notes,
        company_id=officer.company_id,
        is_anomaly=is_anomaly,
    )
    session.commit()

    application, customer, product = _get_application_bundle(session, application_id)
    session.refresh(loan)
    return LoanApprovalResponse(
        application=_to_response(session, application, customer, product),
        loan=LoanResponse(
            id=loan.id,
            application_id=loan.application_id,
            principal=loan.principal,
            interest_rate=loan.interest_rate,
            total_repayable=loan.total_repayable,
            penalties_accrued=loan.penalties_accrued,
            outstanding_balance=loan.outstanding_balance,
            status=loan.status.value,
        ),
        repayment_due_date=due_date,
        repayment_amount_due=loan.total_repayable,
    )


@router.post("/applications/{application_id}/reject", response_model=CreditApplicationResponse)
def reject_application(
    application_id: int,
    body: CreditDecisionRequest,
    session: Session = Depends(get_session),
    officer: User = Depends(require_role(UserRole.credit_officer)),
) -> CreditApplicationResponse:
    _get_application_bundle(session, application_id)  # 404s if not in this company

    result = session.execute(
        update(LoanApplication)
        .where(LoanApplication.id == application_id, LoanApplication.status == ApplicationStatus.pending)
        .values(
            status=ApplicationStatus.rejected,
            reviewed_by=officer.id,
            reviewed_at=datetime.now(timezone.utc),
            review_notes=body.notes,
        )
    )
    if result.rowcount == 0:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Application is not pending review")

    write_audit(
        session,
        actor=officer,
        action=AuditAction.APPLICATION_REJECT.value,
        entity_type="LoanApplication",
        entity_id=application_id,
        reason=body.notes,
        company_id=officer.company_id,
    )
    session.commit()

    application, customer, product = _get_application_bundle(session, application_id)
    return _to_response(session, application, customer, product)


@router.post("/loans/{loan_id}/disburse", response_model=DisbursementResponse)
def disburse_loan(
    loan_id: int,
    session: Session = Depends(get_session),
    officer: User = Depends(require_role(UserRole.credit_officer)),
) -> DisbursementResponse:
    """CLAUDE.md M7: simulated disbursement — no real money moves, but it
    still writes a ledger row (rule #9) and is on the suspension block-list,
    not the allow-list (§6: "new applications / disbursements: stopped")."""
    loan = get_or_404(session, Loan, loan_id, detail="Loan not found")

    now = datetime.now(timezone.utc)
    # CLAUDE.md §14: compare-and-set, never a blind UPDATE.
    result = session.execute(
        update(Loan)
        .where(Loan.id == loan_id, Loan.status == LoanStatus.approved)
        .values(status=LoanStatus.active, disbursed_at=now)
    )
    if result.rowcount == 0:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Loan is not awaiting disbursement")

    session.add(
        Transaction(
            loan_id=loan.id,
            customer_id=loan.customer_id,
            company_id=loan.company_id,
            type=TransactionType.disbursement,
            amount=loan.principal,
        )
    )
    write_audit(
        session,
        actor=officer,
        action=AuditAction.LOAN_DISBURSE.value,
        entity_type="Loan",
        entity_id=loan_id,
        company_id=officer.company_id,
    )
    session.commit()

    session.refresh(loan)
    return DisbursementResponse(
        loan=LoanResponse(
            id=loan.id,
            application_id=loan.application_id,
            principal=loan.principal,
            interest_rate=loan.interest_rate,
            total_repayable=loan.total_repayable,
            penalties_accrued=loan.penalties_accrued,
            outstanding_balance=loan.outstanding_balance,
            status=loan.status.value,
            disbursed_at=loan.disbursed_at,
        )
    )


@router.get("/loans/collections", response_model=list[CollectionsQueueItemResponse])
def get_collections_queue(
    session: Session = Depends(get_session),
    officer: User = Depends(require_role(UserRole.credit_officer, UserRole.system_administrator)),
) -> list[CollectionsQueueItemResponse]:
    """CLAUDE.md §19: collections/delinquency queue — same pattern as every
    other queue (§10), just filtered on status=overdue instead of pending.

    Two queries total (not 1 + 3N): the loans+customer+product join, then
    one grouped follow-up query for every loan's earliest overdue
    installment, keyed by loan_id. The grouped query is intentionally a
    plain top-level `select(RepaymentSchedule...)` rather than a subquery
    embedded in the first join — CLAUDE.md §5's tenant-scoping listener is
    proven (by the isolation suite) to filter every top-level TenantMixin
    select in a statement; keeping RepaymentSchedule as its own top-level
    query removes any doubt about whether that filter also reaches into a
    nested subquery.
    """
    sync_loan_delinquency(session)

    loan_rows = session.exec(
        select(Loan, User, LoanProduct)
        .join(User, User.id == Loan.customer_id)
        .join(LoanProduct, LoanProduct.id == Loan.loan_product_id)
        .where(Loan.status == LoanStatus.overdue)
        .order_by(Loan.id)
    ).all()

    today = date.today()
    loan_ids = [loan.id for loan, _, _ in loan_rows]
    earliest_overdue_by_loan: dict[int, date] = {}
    if loan_ids:
        earliest_overdue_by_loan = dict(
            session.exec(
                select(RepaymentSchedule.loan_id, func.min(RepaymentSchedule.due_date))
                .where(
                    RepaymentSchedule.loan_id.in_(loan_ids),
                    RepaymentSchedule.is_paid.is_(False),
                    RepaymentSchedule.due_date < today,
                )
                .group_by(RepaymentSchedule.loan_id)
            ).all()
        )

    responses = []
    for loan, customer, product in loan_rows:
        earliest_overdue = earliest_overdue_by_loan.get(loan.id)
        if earliest_overdue is None:
            continue
        responses.append(
            CollectionsQueueItemResponse(
                id=loan.id,
                customer_full_name=customer.full_name,
                customer_email=customer.email,
                loan_product_name=product.name,
                outstanding_balance=loan.outstanding_balance,
                status=loan.status.value,
                earliest_overdue_due_date=earliest_overdue,
                days_overdue=(today - earliest_overdue).days,
            )
        )
    return responses


@router.post("/loans/{loan_id}/mark-defaulted", response_model=LoanResponse)
def mark_loan_defaulted(
    loan_id: int,
    body: LoanDefaultRequest,
    session: Session = Depends(get_session),
    officer: User = Depends(require_role(UserRole.credit_officer, UserRole.system_administrator)),
) -> LoanResponse:
    """CLAUDE.md §1/§19: defaulting a loan is always a human decision, never
    automatic — the system only ever proposes 'overdue', staff decide 'default'."""
    loan = get_or_404(session, Loan, loan_id, detail="Loan not found")

    # CLAUDE.md §14: compare-and-set, never a blind UPDATE.
    result = session.execute(
        update(Loan)
        .where(Loan.id == loan_id, Loan.status == LoanStatus.overdue)
        .values(status=LoanStatus.defaulted)
    )
    if result.rowcount == 0:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Loan is not currently overdue")

    write_audit(
        session,
        actor=officer,
        action=AuditAction.LOAN_MARK_DEFAULTED.value,
        entity_type="Loan",
        entity_id=loan_id,
        reason=body.reason,
        company_id=officer.company_id,
    )
    session.commit()

    session.refresh(loan)
    return LoanResponse(
        id=loan.id,
        application_id=loan.application_id,
        principal=loan.principal,
        interest_rate=loan.interest_rate,
        total_repayable=loan.total_repayable,
        penalties_accrued=loan.penalties_accrued,
        outstanding_balance=loan.outstanding_balance,
        status=loan.status.value,
        disbursed_at=loan.disbursed_at,
    )
